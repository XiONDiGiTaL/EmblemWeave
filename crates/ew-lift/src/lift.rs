fn reg_read(i: u8, sp_ok: bool) -> String {
    format!("EW_R(cpu, {i}, {})", if sp_ok { 1 } else { 0 })
}

fn reg_write(i: u8, sp_ok: bool, value: &str) -> String {
    format!("EW_W(cpu, {i}, {}, {value});", if sp_ok { 1 } else { 0 })
}

fn masked(is64: bool, expr: &str) -> String {
    if is64 {
        expr.to_string()
    } else {
        format!("EW_M32({expr})")
    }
}

/// Emit a byte-for-byte transfer between guest memory and a SIMD/FP register.
/// Sixteen-byte transfers move both halves explicitly, because the generated C
/// has no 128-bit integer type to lean on.
fn vector_transfer_line(reg: u8, addr: &str, bytes: u8, load: bool) -> String {
    if load {
        if bytes == 16 {
            format!(
                "      {{ ew_u64 lo_ = ew_load(cpu, {addr}, 8); ew_u64 hi_ = ew_load(cpu, ({addr}) + 8, 8); ew_vset128(cpu, {reg}, lo_, hi_); }}\n"
            )
        } else {
            format!("      ew_vset(cpu, {reg}, {bytes}, ew_load(cpu, {addr}, {bytes}));\n")
        }
    } else if bytes == 16 {
        format!(
            "      {{ ew_u64 lo_ = cpu->v[{reg} & 31u][0]; ew_u64 hi_ = cpu->v[{reg} & 31u][1]; ew_store(cpu, {addr}, lo_, 8); ew_store(cpu, ({addr}) + 8, hi_, 8); }}\n"
        )
    } else {
        format!("      ew_store(cpu, {addr}, ew_vget(cpu, {reg}, {bytes}), {bytes});\n")
    }
}

fn emit_vector_transfer(
    out: &mut String,
    a: u64,
    rt: u8,
    bytes: u8,
    load: bool,
    ea: &str,
    writeback: Option<(u8, i64, String)>,
) {
    out.push_str(&format!(
        "    /* 0x{a:x}: {} v{rt}, [{ea}] ({bytes} bytes) */\n    {{ ew_u64 ea_ = {ea};\n",
        if load { "ldr" } else { "str" }
    ));
    out.push_str(&vector_transfer_line(rt, "ea_", bytes, load));
    match writeback {
        Some((rn, offset, base)) => out.push_str(&format!(
            "      EW_W(cpu, {rn}, 1, ({base}) + {}); }}\n",
            offset as i64
        )),
        None => out.push_str("    }\n"),
    }
}

fn emit_insn(
    out: &mut String,
    insn: &Insn,
    func: &LiftedFunction,
    table: Option<&crate::jump_table::JumpTable>,
) {
    let a = insn.addr;
    match insn.op {
        Op::Nop => out.push_str(&format!("    /* 0x{a:x}: nop */\n")),
        Op::B { target } => {
            // A branch inside the recovered block set continues in this
            // function; a branch out of it hands control to the dispatcher.
            let next = if func.contains(target) { "continue;" } else { "return 1;" };
            out.push_str(&format!(
                "    /* 0x{a:x}: b 0x{target:x} */\n    cpu->pc = 0x{target:x}ULL;\n    {next}\n"
            ));
        }
        Op::Bl { target } => {
            out.push_str(&format!(
                "    /* 0x{a:x}: bl 0x{target:x} */\n    cpu->x[30] = 0x{:x}ULL;\n    cpu->pc = 0x{target:x}ULL;\n    return 1;\n",
                a + 4
            ));
        }
        Op::BCond { cond, target } => {
            let next = if func.contains(target) { "continue;" } else { "return 1;" };
            out.push_str(&format!(
                "    /* 0x{a:x}: b.{} 0x{target:x} */\n    if (ew_cond(cpu, {})) {{ cpu->pc = 0x{target:x}ULL; {next} }}\n",
                cond.c_suffix(),
                cond as u32
            ));
        }
        Op::CompareBranchZero { rt, target, nonzero, is64 } => {
            let v = masked(is64, &reg_read(rt, false));
            let cond = if nonzero { "!=" } else { "==" };
            let next = if func.contains(target) { "continue;" } else { "return 1;" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rt}, 0x{target:x} */\n    if (({v} {cond} 0ULL)) {{ cpu->pc = 0x{target:x}ULL; {next} }}\n",
                if nonzero { "cbnz" } else { "cbz" }
            ));
        }
        Op::TestBitBranch { rt, bit, target, nonzero } => {
            let v = reg_read(rt, false);
            // tbnz branches when the bit is set, tbz when it is clear.
            let cond = if nonzero { "!=" } else { "==" };
            let next = if func.contains(target) { "continue;" } else { "return 1;" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rt}, #{bit}, 0x{target:x} */\n    if (((({v} >> {bit}) & 1ULL) {cond} 0ULL)) {{ cpu->pc = 0x{target:x}ULL; {next} }}\n",
                if nonzero { "tbnz" } else { "tbz" }
            ));
        }
        Op::Br { rn } => {
            match table {
                // A resolved table turns an indirect branch into a dispatch on
                // the branch register, so the next block runs in this function.
                Some(t) => {
                    out.push_str(&format!(
                        "    /* 0x{a:x}: br x{rn} via jump table 0x{:x}, {} entries */\n    switch ({}) {{\n",
                        t.table,
                        t.entries,
                        reg_read(rn, false)
                    ));
                    for target in &t.targets {
                        let next = if func.contains(*target) { "continue;" } else { "return 1;" };
                        out.push_str(&format!(
                            "    case 0x{target:x}ULL: cpu->pc = 0x{target:x}ULL; {next}\n"
                        ));
                    }
                    out.push_str("    default: return 1; /* table target not recovered */\n    }\n");
                }
                None => out.push_str(&format!(
                    "    /* 0x{a:x}: br x{rn} (unresolved) */\n    cpu->pc = {};\n    return 1;\n",
                    reg_read(rn, false)
                )),
            }
        }
        Op::Blr { rn } => out.push_str(&format!(
            "    /* 0x{a:x}: blr x{rn} */\n    cpu->x[30] = 0x{:x}ULL;\n    cpu->pc = {};\n    return 1;\n",
            a + 4,
            reg_read(rn, false)
        )),
        Op::Ret { rn } => out.push_str(&format!(
            "    /* 0x{a:x}: ret x{rn} */\n    cpu->pc = {};\n    return 1;\n",
            reg_read(rn, false)
        )),
        Op::Adr { rd, target } => out.push_str(&format!(
            "    /* 0x{a:x}: adr x{rd}, 0x{target:x} */\n    {}\n",
            reg_write(rd, false, &format!("0x{target:x}ULL"))
        )),
        Op::MoveWide { rd, imm, shift, kind, is64 } => {
            let cur = masked(is64, &reg_read(rd, false));
            let expr = match kind {
                0 => format!("0x{:x}ULL", (imm as u64) << shift),
                1 => format!("~0x{:x}ULL", (imm as u64) << shift),
                _ => format!("(({cur} & ~(0xFFFFULL << {shift})) | (0x{:x}ULL << {shift}))", imm),
            };
            let mnemonic = match kind {
                0 => "movz",
                1 => "movn",
                _ => "movk",
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {mnemonic} x{rd}, #0x{imm:x}, lsl #{shift} */\n    {}\n",
                reg_write(rd, false, &masked(is64, &expr))
            ));
        }
        Op::AddSubImm { rd, rn, imm, sub, set_flags, is64 } => {
            // With S=0, rd/rn 31 means SP; with S=1 it means XZR.
            let sp_ok = !set_flags;
            let a_expr = reg_read(rn, sp_ok);
            let op_str = if sub { "-" } else { "+" };
            let r_expr = masked(is64, &format!("({a_expr} {op_str} 0x{imm:x}ULL)"));
            let mnemonic = match (sub, set_flags) {
                (false, false) => "add",
                (true, false) => "sub",
                (false, true) => "adds",
                (true, true) => "subs",
            };
            let flag_fn = if sub { "ew_flags_sub" } else { "ew_flags_add" };
            out.push_str(&format!("    /* 0x{a:x}: {mnemonic} x{rd}, x{rn}, #0x{imm:x} */\n"));
            if set_flags {
                out.push_str(&format!(
                    "    {{ ew_u64 a_ = {a_expr}; ew_u64 r_ = {r_expr}; {flag_fn}(cpu, a_, 0x{imm:x}ULL, r_, {}); {}\n",
                    if is64 { 1 } else { 0 },
                    reg_write(rd, sp_ok, "r_")
                ));
                out.pop();
                out.push_str("}\n");
            } else {
                out.push_str(&format!("    {{ ew_u64 r_ = {r_expr}; {} }}\n", reg_write(rd, sp_ok, "r_")));
            }
        }
        Op::AddSubReg { rd, rn, rm, shift, amount, sub, set_flags, is64 } => {
            let a_expr = reg_read(rn, false);
            let b_expr = format!(
                "ew_shift({}, {}, {}, {})",
                reg_read(rm, false),
                shift as u32,
                amount,
                if is64 { 1 } else { 0 }
            );
            let op_str = if sub { "-" } else { "+" };
            let r_expr = masked(is64, &format!("(a_ {op_str} b_)"));
            let flag_fn = if sub { "ew_flags_sub" } else { "ew_flags_add" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rd}, x{rn}, x{rm}, {} #{amount} */\n    {{ ew_u64 a_ = {a_expr}; ew_u64 b_ = {b_expr}; ew_u64 r_ = {r_expr};",
                if sub { "sub" } else { "add" },
                shift_name(shift)
            ));
            if set_flags {
                out.push_str(&format!(
                    " {flag_fn}(cpu, a_, b_, r_, {});",
                    if is64 { 1 } else { 0 }
                ));
            }
            out.push_str(&format!(" {} }}\n", reg_write(rd, false, "r_")));
        }
        Op::AddSubExt { rd, rn, rm, option, shift, sub, set_flags, is64 } => {
            let a_expr = reg_read(rn, false);
            let b_expr = format!(
                "(ew_extend({}, {}) << {shift})",
                reg_read(rm, false),
                option as u32
            );
            let op_str = if sub { "-" } else { "+" };
            let r_expr = masked(is64, &format!("(a_ {op_str} b_)"));
            let flag_fn = if sub { "ew_flags_sub" } else { "ew_flags_add" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {mnemonic} x{rd}, x{rn}, x{rm}, extend {opt}, lsl #{shift} */\n    {{ ew_u64 a_ = {a_expr}; ew_u64 b_ = {b_expr}; ew_u64 r_ = {r_expr};",
                mnemonic = if sub { "sub" } else { "add" },
                opt = option as u32
            ));
            if set_flags {
                out.push_str(&format!(
                    " {flag_fn}(cpu, a_, b_, r_, {});",
                    if is64 { 1 } else { 0 }
                ));
            }
            out.push_str(&format!(" {} }}\n", reg_write(rd, false, "r_")));
        }
        Op::Bitfield { rd, rn, immr, imms, opc, is64 } => {
            let mnemonic = match opc {
                0 => "sbfm",
                1 => "bfm",
                _ => "ubfm",
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {mnemonic} x{rd}, x{rn}, #immr {immr}, #imms {imms} */\n    {{ ew_u64 src_ = {}; ew_u64 dst_ = {}; {} }}\n",
                reg_read(rn, false),
                reg_read(rd, false),
                reg_write(
                    rd,
                    false,
                    &format!(
                        "ew_bitfield(src_, dst_, {immr}, {imms}, {opc}, {})",
                        if is64 { 1 } else { 0 }
                    )
                )
            ));
        }
        Op::LogicalImm { rd, rn, imm, op, set_flags, is64 } => {
            let a_expr = reg_read(rn, false);
            let sym = match op {
                LogicalOp::And => "&",
                LogicalOp::Orr => "|",
                LogicalOp::Eor => "^",
                LogicalOp::Ands => "&",
            };
            let r_expr = masked(is64, &format!("(a_ {sym} 0x{imm:x}ULL)"));
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rd}, x{rn}, #0x{imm:x} */\n    {{ ew_u64 a_ = {a_expr}; ew_u64 r_ = {r_expr};",
                logical_name(op)
            ));
            if set_flags || op == LogicalOp::Ands {
                out.push_str(&format!(" ew_flags_nz(cpu, r_, {});", if is64 { 1 } else { 0 }));
            }
            out.push_str(&format!(" {} }}\n", reg_write(rd, false, "r_")));
        }
        Op::LogicalReg { rd, rn, rm, shift, amount, op, set_flags, is64, invert } => {
            let a_expr = reg_read(rn, false);
            let b_expr = format!(
                "ew_shift({}, {}, {}, {})",
                reg_read(rm, false),
                shift as u32,
                amount,
                if is64 { 1 } else { 0 }
            );
            let b_expr = if invert { masked(is64, &format!("(~{b_expr})")) } else { b_expr };
            let sym = match op {
                LogicalOp::And => "&",
                LogicalOp::Orr => "|",
                LogicalOp::Eor => "^",
                LogicalOp::Ands => "&",
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rd}, x{rn}, x{rm} */\n    {{ ew_u64 a_ = {a_expr}; ew_u64 b_ = {b_expr}; ew_u64 r_ = {};",
                logical_name(op),
                masked(is64, &format!("(a_ {sym} b_)"))
            ));
            if set_flags || op == LogicalOp::Ands {
                out.push_str(&format!(" ew_flags_nz(cpu, r_, {});", if is64 { 1 } else { 0 }));
            }
            out.push_str(&format!(" {} }}\n", reg_write(rd, false, "r_")));
        }
        Op::MulLong { rd, rn, rm, ra, sub, unsigned } => {
            let product = if unsigned {
                format!(
                    "((ew_u64)EW_M32({}) * (ew_u64)EW_M32({}))",
                    reg_read(rn, false),
                    reg_read(rm, false)
                )
            } else {
                format!(
                    "((ew_u64)((ew_i64)(int32_t)EW_M32({}) * (ew_i64)(int32_t)EW_M32({})))",
                    reg_read(rn, false),
                    reg_read(rm, false)
                )
            };
            let op_str = if sub { "-" } else { "+" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rd}, w{rn}, w{rm}, x{ra} */\n    {{ ew_u64 acc_ = {}; ew_u64 p_ = {product}; {} }}\n",
                match (unsigned, sub) {
                    (false, false) => "smaddl",
                    (false, true) => "smsubl",
                    (true, false) => "umaddl",
                    (true, true) => "umsubl",
                },
                reg_read(ra, false),
                reg_write(rd, false, &format!("(acc_ {op_str} p_)"))
            ));
        }
        Op::DataProc2 { rd, rn, rm, op, is64 } => {
            let a_expr = reg_read(rn, false);
            let b_expr = reg_read(rm, false);
            let expr = match op {
                DataOp2::Udiv => format!("ew_udiv({a_expr}, {b_expr})"),
                DataOp2::Sdiv => format!(
                    "ew_sdiv({a_expr}, {b_expr}, {})",
                    if is64 { 1 } else { 0 }
                ),
                DataOp2::Lslv => format!(
                    "ew_shift({a_expr}, 0, (unsigned){b_expr}, {})",
                    if is64 { 1 } else { 0 }
                ),
                DataOp2::Lsrv => format!(
                    "ew_shift({a_expr}, 1, (unsigned){b_expr}, {})",
                    if is64 { 1 } else { 0 }
                ),
                DataOp2::Asrv => format!(
                    "ew_shift({a_expr}, 2, (unsigned){b_expr}, {})",
                    if is64 { 1 } else { 0 }
                ),
                DataOp2::Rorv => format!(
                    "ew_shift({a_expr}, 3, (unsigned){b_expr}, {})",
                    if is64 { 1 } else { 0 }
                ),
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rd}, x{rn}, x{rm} */\n    {{ ew_u64 r_ = {}; {} }}\n",
                op.c_name(),
                masked(is64, &expr),
                reg_write(rd, false, "r_")
            ));
        }
        Op::MultiplyAdd { rd, rn, rm, ra, sub, is64 } => {
            let op_str = if sub { "-" } else { "+" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rd}, x{rn}, x{rm}, x{ra} */\n    {{ ew_u64 prod_ = {} * {}; ew_u64 acc_ = {}; ew_u64 r_ = {}; {} }}\n",
                if sub { "msub" } else { "madd" },
                reg_read(rn, false),
                reg_read(rm, false),
                reg_read(ra, false),
                masked(is64, &format!("(acc_ {op_str} prod_)")),
                reg_write(rd, false, "r_")
            ));
        }
        Op::CondSelect { rd, rn, rm, cond, kind, is64 } => {
            let alt = match kind {
                0 => "1".to_string(),
                1 => "2".to_string(),
                2 => "3".to_string(),
                _ => "4".to_string(),
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: cs{} ({alt}) x{rd}, x{rn}, x{rm}, {} */\n",
                cond.c_suffix(),
                cond as u32
            ));
            out.push_str(&format!(
                "    {{ ew_u64 a_ = {}; ew_u64 b_ = {}; ew_u64 r_ = ew_condsel(cpu, {}, a_, b_, {alt}, {}); {} }}\n",
                reg_read(rn, false),
                reg_read(rm, false),
                cond as u32,
                if is64 { 1 } else { 0 },
                reg_write(rd, false, "r_")
            ));
        }
        Op::LoadStore { rt, rn, offset, bytes, load, signed, mode, is64 } => {
            let base = reg_read(rn, true);
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rt}, [x{rn}, #{offset}] ({} bytes{}) */\n",
                match (load, signed) {
                    (false, _) => "str",
                    (true, false) => "ldr",
                    (true, true) => "ldrs",
                },
                bytes,
                if signed { ", sign extended" } else { "" }
            ));
            // Post-indexed forms address `base` and write back afterwards;
            // offset/pre-indexed forms address `base + offset`.
            let ea = match mode {
                MemMode::PostIndex => base.clone(),
                _ => format!("({base} + {})", offset as i64),
            };
            out.push_str(&format!("    {{ ew_u64 ea_ = {ea};\n"));
            if load {
                let value = if signed {
                    masked(is64, &format!("ew_sext(v_, {}, {})", bytes * 8 - 1, is64 as u32))
                } else {
                    masked(is64, "v_")
                };
                out.push_str(&format!(
                    "      ew_u64 v_ = ew_load(cpu, ea_, {bytes}); {} }}\n",
                    reg_write(rt, false, &value)
                ));
            } else {
                out.push_str(&format!(
                    "      ew_store(cpu, ea_, {}, {bytes}); }}\n",
                    masked(is64, &reg_read(rt, false))
                ));
            }
            // Index writeback for pre/post indexed forms.
            match mode {
                MemMode::PreIndex | MemMode::PostIndex => {
                    out.push_str(&format!(
                        "    {}\n",
                        reg_write(rn, true, &format!("({base} + {offset})"))
                    ));
                }
                MemMode::Offset => {}
            }
        }
        Op::LoadStorePair { rt, rt2, rn, offset, load, mode, is64 } => {
            let base = reg_read(rn, true);
            let width = if is64 { 8 } else { 4 };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rt}, x{rt2}, [x{rn}, #{offset}] */\n",
                if load { "ldp" } else { "stp" }
            ));
            let ea = match mode {
                MemMode::PostIndex => base.clone(),
                _ => format!("({base} + {offset})"),
            };
            out.push_str(&format!("    {{ ew_u64 ea_ = {ea};\n"));
            if load {
                out.push_str(&format!(
                    "      ew_u64 v1_ = ew_load(cpu, ea_, {width});\n      ew_u64 v2_ = ew_load(cpu, ea_ + {width}, {width});\n      {} {}\n",
                    reg_write(rt, false, &masked(is64, "v1_")),
                    reg_write(rt2, false, &masked(is64, "v2_"))
                ));
            } else {
                out.push_str(&format!(
                    "      ew_store(cpu, ea_, {}, {width});\n      ew_store(cpu, ea_ + {width}, {}, {width});\n",
                    masked(is64, &reg_read(rt, false)),
                    masked(is64, &reg_read(rt2, false))
                ));
            }
            out.push_str("    }\n");
            if mode != MemMode::Offset {
                out.push_str(&format!("    {}\n", reg_write(rn, true, &format!("({base} + {offset})"))));
            }
        }
        Op::LoadPairSigned { rt, rt2, rn, offset, mode } => {
            let base = reg_read(rn, true);
            let ea = match mode {
                MemMode::PostIndex => base.clone(),
                _ => format!("({base} + {offset})"),
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: ldpsw x{rt}, x{rt2}, [x{rn}, #{offset}] */
    {{ ew_u64 ea_ = {ea};
      ew_u64 v1_ = (ew_u64)(ew_i64)(ew_i32)(ew_u32)ew_load(cpu, ea_, 4);
      ew_u64 v2_ = (ew_u64)(ew_i64)(ew_i32)(ew_u32)ew_load(cpu, ea_ + 4, 4);
      {} {}
    }}
",
                reg_write(rt, false, "v1_"),
                reg_write(rt2, false, "v2_")
            ));
            if mode != MemMode::Offset {
                out.push_str(&format!("    {}
", reg_write(rn, true, &format!("({base} + {offset})"))));
            }
        }
        Op::LoadStoreReg { rt, rn, rm, option, shift, bytes, load, signed, is64 } => {
            let base = reg_read(rn, true);
            let ea = format!(
                "({base} + (ew_extend({}, {}) << {shift}))",
                reg_read(rm, false),
                option as u32
            );
            out.push_str(&format!(
                "    /* 0x{a:x}: {mnemonic} x{rt}, [x{rn}, x{rm}, extend {opt}, lsl #{shift}] */\n    {{ ew_u64 ea_ = {ea};\n",
                mnemonic = match (load, signed) {
                    (false, _) => "str",
                    (true, false) => "ldr",
                    (true, true) => "ldrs",
                },
                opt = option as u32
            ));
            if load {
                let value = if signed {
                    masked(is64, &format!("ew_sext(v_, {}, {})", bytes * 8 - 1, is64 as u32))
                } else {
                    masked(is64, "v_")
                };
                out.push_str(&format!(
                    "      ew_u64 v_ = ew_load(cpu, ea_, {bytes}); {} }}\n",
                    reg_write(rt, false, &value)
                ));
            } else {
                out.push_str(&format!(
                    "      ew_store(cpu, ea_, {}, {bytes}); }}\n",
                    masked(is64, &reg_read(rt, false))
                ));
            }
        }
        Op::BitScan { rd, rn, op, is64 } => {
            let src = reg_read(rn, false);
            let expr = match op {
                crate::aarch64::BitScan::Rbit => format!("ew_rbit({src}, {})", is64 as u32),
                crate::aarch64::BitScan::Rev => {
                    if is64 {
                        format!("ew_rev_within({src}, 8, 1)")
                    } else {
                        format!("ew_rev_within({src}, 4, 0)")
                    }
                }
                crate::aarch64::BitScan::Rev32 => {
                    format!("ew_rev_within({src}, 4, {})", is64 as u32)
                }
                crate::aarch64::BitScan::Rev16 => {
                    format!("ew_rev_within({src}, 2, {})", is64 as u32)
                }
                crate::aarch64::BitScan::Clz => format!("ew_clz({src}, {})", is64 as u32),
                crate::aarch64::BitScan::Cls => format!("ew_cls({src}, {})", is64 as u32),
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rd}, x{rn} */\n    {{ ew_u64 r_ = {}; {} }}\n",
                op.c_name(),
                masked(is64, &expr),
                reg_write(rd, false, "r_")
            ));
        }
        Op::Crc32 { rd, rn, rm, bytes, castagnoli } => {
            let width = match bytes {
                1 => "b",
                2 => "h",
                4 => "w",
                _ => "x",
            };
            let poly = if castagnoli { "0x82F63B78u" } else { "0xEDB88320u" };
            out.push_str(&format!(
                "    /* 0x{a:x}: crc32{width}{} w{rd}, w{rn}, w{rm} */\n    {{ ew_u64 r_ = ew_crc32({}, {}, {bytes}, {poly}); {} }}\n",
                if castagnoli { "c" } else { "" },
                reg_read(rn, false),
                reg_read(rm, bytes == 8),
                reg_write(rd, false, "r_")
            ));
        }
        Op::CondCompare { rn, rm, imm5, immediate, cond, nzcv, sub, is64 } => {
            let a_expr = reg_read(rn, false);
            let b = if immediate {
                format!("{}ULL", imm5)
            } else {
                reg_read(rm, false)
            };
            let flags = if sub { "ew_flags_sub" } else { "ew_flags_add" };
            let arith = if sub { "-" } else { "+" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {name} x{rn}, {rhs}, #{nzcv}, {cond} */\n    {{ ew_u64 a_ = {a_expr}; ew_u64 b_ = {b}; ew_u64 r_ = EW_M({m64}, a_ {arith} b_); if (ew_cond(cpu, {cond_bit})) {{ {flags}(cpu, a_, b_, r_, {m64}); }} else {{ cpu->nzcv = {nzcv}u; }} }}\n",
                name = if sub { "ccmp" } else { "ccmn" },
                rhs = if immediate { format!("#{imm5}") } else { format!("x{rm}") },
                cond = cond.c_suffix(),
                cond_bit = cond as u32,
                m64 = if is64 { 1 } else { 0 },
                nzcv = nzcv,
            ));
        }
        Op::AtomicRmw { rs, rt, rn, op, order, bytes } => {
            let width = bytes as u32 * 8;
            // The operand at the access width; the old value is loaded at that
            // width already, and it is what the destination register gets.
            let mask = if bytes == 8 { "~0ULL".to_string() } else { format!("0x{:x}ULL", (1u64 << width) - 1) };
            let op_expr = match op {
                crate::aarch64::AtomicOp::Add => "old_ + v_".to_string(),
                crate::aarch64::AtomicOp::Clr => "old_ & ~v_".to_string(),
                crate::aarch64::AtomicOp::Eor => "old_ ^ v_".to_string(),
                crate::aarch64::AtomicOp::Set => "old_ | v_".to_string(),
                crate::aarch64::AtomicOp::SMax => format!(
                    "(ew_sext(old_, {t}, 1) > ew_sext(v_, {t}, 1)) ? old_ : v_",
                    t = width - 1
                ),
                crate::aarch64::AtomicOp::SMin => format!(
                    "(ew_sext(old_, {t}, 1) < ew_sext(v_, {t}, 1)) ? old_ : v_",
                    t = width - 1
                ),
                crate::aarch64::AtomicOp::UMax => "(old_ > v_) ? old_ : v_".to_string(),
                crate::aarch64::AtomicOp::UMin => "(old_ < v_) ? old_ : v_".to_string(),
                crate::aarch64::AtomicOp::Swap => "v_".to_string(),
            };
            let mnemonic = match op {
                crate::aarch64::AtomicOp::Swap => "swp".to_string(),
                other => format!("ld{}", other.c_name()),
            };
            let ordering = match (order.acquire, order.release) {
                (true, true) => "al",
                (true, false) => "a",
                (false, true) => "l",
                (false, false) => "",
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {mnemonic}{ordering} x{rs}, x{rt}, [x{rn}] ({bytes} bytes) */\n    {{ ew_u64 ea_ = {base}; ew_u64 old_ = ew_load(cpu, ea_, {bytes}); ew_u64 v_ = ({operand}) & {mask}; ew_u64 new_ = {op_expr}; ew_store(cpu, ea_, new_, {bytes}); {dest} }}\n",
                base = reg_read(rn, true),
                operand = reg_read(rs, false),
                dest = reg_write(rt, false, "old_"),
            ));
        }
        Op::VectorLoadStore { rt, rn, offset, bytes, load, mode } => {
            let base = reg_read(rn, true);
            let ea = match mode {
                MemMode::PostIndex => base.clone(),
                _ => format!("({base} + {})", offset as i64),
            };
            let writeback = if mode == MemMode::Offset {
                None
            } else {
                Some((rn, offset, base.clone()))
            };
            emit_vector_transfer(out, a, rt, bytes, load, &ea, writeback);
        }
        Op::VectorLoadStoreReg { rt, rn, rm, option, shift, bytes, load } => {
            let ea = format!(
                "({} + (ew_extend({}, {}) << {shift}))",
                reg_read(rn, true),
                reg_read(rm, false),
                option as u32
            );
            emit_vector_transfer(out, a, rt, bytes, load, &ea, None);
        }
        Op::VectorLoadStorePair { rt, rt2, rn, offset, bytes, load, mode } => {
            let base = reg_read(rn, true);
            let ea = match mode {
                MemMode::PostIndex => base.clone(),
                _ => format!("({base} + {})", offset as i64),
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rt}, x{rt2}, [x{rn}] ({} bytes each) */\n    {{ ew_u64 ea_ = {ea};\n",
                if load { "ldp" } else { "stp" },
                bytes
            ));
            for (n, reg) in [(0u64, rt), (1u64, rt2)] {
                let at = if n == 0 {
                    "ea_".to_string()
                } else {
                    format!("ea_ + {}", n * bytes as u64)
                };
                out.push_str(&vector_transfer_line(reg, &at, bytes, load));
            }
            if mode != MemMode::Offset {
                out.push_str(&format!(
                    "      EW_W(cpu, {rn}, 1, {base} + {}); }}\n",
                    offset as i64
                ));
            } else {
                out.push_str("    }\n");
            }
        }
        Op::VectorZero { rd, full } => {
            out.push_str(&format!(
                "    /* 0x{a:x}: movi {}, #0 */\n    ew_vset128(cpu, {rd}, 0, 0);\n",
                if full { "v.2d" } else { "d" }
            ));
        }
        Op::FpMoveGp { fp, gp, to_fp, is64 } => {
            let bytes = if is64 { 8 } else { 4 };
            if to_fp {
                out.push_str(&format!(
                    "    /* 0x{a:x}: fmov {}, {} */\n    ew_vset(cpu, {fp}, {bytes}, {});\n",
                    if is64 { "d" } else { "s" },
                    if is64 { format!("x{gp}") } else { format!("w{gp}") },
                    reg_read(gp, false)
                ));
            } else {
                let raw = format!("ew_vget(cpu, {fp}, {bytes})");
                let value = if is64 { raw } else { format!("EW_M32({raw})") };
                out.push_str(&format!(
                    "    /* 0x{a:x}: fmov {gp_name}, {fp_name} */\n    {{ ew_u64 r_ = {value}; {dest} }}\n",
                    gp_name = if is64 { format!("x{gp}") } else { format!("w{gp}") },
                    fp_name = if is64 { "d" } else { "s" },
                    dest = reg_write(gp, false, "r_"),
                ));
            }
        }
        Op::FpCopy { rd, rn, is64 } => {
            let bytes = if is64 { 8 } else { 4 };
            out.push_str(&format!(
                "    /* 0x{a:x}: fmov {}, {} */\n    ew_vset(cpu, {rd}, {bytes}, ew_vget(cpu, {rn}, {bytes}));\n",
                if is64 { "d" } else { "s" },
                if is64 { format!("d{rn}") } else { format!("s{rn}") }
            ));
        }
        Op::FpBinary { rd, rn, rm, op, is64 } => {
            let width = if is64 { "d" } else { "s" };
            let (get, set) = if is64 { ("ew_dget", "ew_dset") } else { ("ew_sget", "ew_sset") };
            let lhs = format!("{get}(cpu, {rn})");
            let rhs = format!("{get}(cpu, {rm})");
            let expr = match op {
                FpBinop::Mul => format!("({lhs} * {rhs})"),
                FpBinop::Div => format!("({lhs} / {rhs})"),
                FpBinop::Add => format!("({lhs} + {rhs})"),
                FpBinop::Sub => format!("({lhs} - {rhs})"),
                FpBinop::NegMul => format!("-({lhs} * {rhs})"),
                FpBinop::Max | FpBinop::MaxNm => {
                    format!("ew_fmax{}({lhs}, {rhs})", if is64 { 64 } else { 32 })
                }
                FpBinop::Min | FpBinop::MinNm => {
                    format!("ew_fmin{}({lhs}, {rhs})", if is64 { 64 } else { 32 })
                }
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} {width}{rd}, {width}{rn}, {width}{rm} */\n    {set}(cpu, {rd}, {expr});\n",
                fp_binop_name(op)
            ));
        }
        Op::FpUnary { rd, rn, op, is64 } => {
            let width = if is64 { "d" } else { "s" };
            if op == FpUnop::Cvt {
                // The destination width is the opposite of the source width.
                if is64 {
                    out.push_str(&format!(
                        "    /* 0x{a:x}: fcvt s{rd}, d{rn} */\n    ew_sset(cpu, {rd}, (float)ew_dget(cpu, {rn}));\n"
                    ));
                } else {
                    out.push_str(&format!(
                        "    /* 0x{a:x}: fcvt d{rd}, s{rn} */\n    ew_dset(cpu, {rd}, (double)ew_sget(cpu, {rn}));\n"
                    ));
                }
                return;
            }
            let (get, set) = if is64 { ("ew_dget", "ew_dset") } else { ("ew_sget", "ew_sset") };
            // C spells the library functions with an `f` suffix for float.
            let lib = if is64 { "" } else { "f" };
            let x = format!("{get}(cpu, {rn})");
            let expr = match op {
                FpUnop::Neg => format!("-{x}"),
                FpUnop::Abs => format!("fabs{lib}({x})"),
                FpUnop::Sqrt => format!("sqrt{lib}({x})"),
                FpUnop::RoundN | FpUnop::RoundX | FpUnop::RoundI => format!("rint{lib}({x})"),
                FpUnop::RoundA => format!("round{lib}({x})"),
                FpUnop::RoundP => format!("ceil{lib}({x})"),
                FpUnop::RoundM => format!("floor{lib}({x})"),
                FpUnop::RoundZ => format!("trunc{lib}({x})"),
                FpUnop::Cvt => x,
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} {width}{rd}, {width}{rn} */\n    {set}(cpu, {rd}, {expr});\n",
                fp_unop_name(op)
            ));
        }
        Op::FpCompare { rn, rm, is64, signal } => {
            let width = if is64 { "d" } else { "s" };
            let ty = if is64 { "double" } else { "float" };
            let get = if is64 { "ew_dget" } else { "ew_sget" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} {width}{rn}, {width}{rm} */\n    {{ {ty} a_ = {get}(cpu, {rn}), b_ = {get}(cpu, {rm});\n      ew_fp_flags(cpu, a_ != a_ || b_ != b_, a_ == b_, a_ < b_, a_ > b_); }}\n",
                if signal { "fcmpe" } else { "fcmp" }
            ));
        }
        Op::FpCompareZero { rn, is64, signal } => {
            let width = if is64 { "d" } else { "s" };
            let ty = if is64 { "double" } else { "float" };
            let get = if is64 { "ew_dget" } else { "ew_sget" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} {width}{rn}, #0.0 */\n    {{ {ty} a_ = {get}(cpu, {rn});\n      ew_fp_flags(cpu, a_ != a_, a_ == 0.0, a_ < 0.0, a_ > 0.0); }}\n",
                if signal { "fcmpe" } else { "fcmp" }
            ));
        }
        Op::FpCondCompare { rn, rm, cond, nzcv, is64 } => {
            let width = if is64 { "d" } else { "s" };
            let ty = if is64 { "double" } else { "float" };
            let get = if is64 { "ew_dget" } else { "ew_sget" };
            out.push_str(&format!(
                "    /* 0x{a:x}: fccmp {width}{rn}, {width}{rm}, #{nzcv}, cond{cond:?} */\n    if (ew_cond(cpu, {})) {{\n      {ty} a_ = {get}(cpu, {rn}), b_ = {get}(cpu, {rm});\n      ew_fp_flags(cpu, a_ != a_ || b_ != b_, a_ == b_, a_ < b_, a_ > b_);\n    }} else {{\n      cpu->nzcv = {nzcv}u;\n    }}\n",
                cond as u32
            ));
        }
        Op::FpCondSelect { rd, rn, rm, cond, is64 } => {
            let width = if is64 { "d" } else { "s" };
            let (get, set) = if is64 { ("ew_dget", "ew_dset") } else { ("ew_sget", "ew_sset") };
            out.push_str(&format!(
                "    /* 0x{a:x}: fcsel {width}{rd}, {width}{rn}, {width}{rm}, cond{cond:?} */\n    {set}(cpu, {rd}, ew_cond(cpu, {}) ? {get}(cpu, {rn}) : {get}(cpu, {rm}));\n",
                cond as u32
            ));
        }
        Op::FpToInt { rd, rn, round, unsigned, src_is64, dest_is64 } => {
            let get = if src_is64 { "ew_dget" } else { "ew_sget" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} x{rd}, {}{rn} */\n    {} }}\n",
                fp_round_name(round, unsigned, dest_is64),
                if src_is64 { "d" } else { "s" },
                format!(
                    "{{ ew_u64 r_ = ew_fp_to_int((double){get}(cpu, {rn}), {}, {}, {});\n      {}",
                    round.c_code(),
                    if dest_is64 { 1 } else { 0 },
                    if unsigned { 1 } else { 0 },
                    reg_write(rd, false, "r_")
                )
            ));
        }
        Op::IntToFp { rd, rn, unsigned, src_is64, dest_is64 } => {
            let bytes = if dest_is64 { 8 } else { 4 };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} {}{rd}, x{rn} */\n    ew_vset(cpu, {rd}, {bytes}, ew_int_to_fp({}, {}, {}, {}));\n",
                if unsigned { "ucvtf" } else { "scvtf" },
                if dest_is64 { "d" } else { "s" },
                reg_read(rn, false),
                if src_is64 { 1 } else { 0 },
                if unsigned { 1 } else { 0 },
                if dest_is64 { 1 } else { 0 }
            ));
        }
        Op::IntToFpFixed { rd, rn, unsigned, src_is64, dest_is64, fbits } => {
            let bytes = if dest_is64 { 8 } else { 4 };
            out.push_str(&format!(
                "    /* 0x{a:x}: fixed-point {}cvtf, #{fbits} */\n    ew_vset(cpu, {rd}, {bytes}, ew_int_to_fp_fixed({}, {}, {}, {}, {fbits}));\n",
                if unsigned { "u" } else { "s" },
                reg_read(rn, false),
                src_is64 as u8,
                unsigned as u8,
                dest_is64 as u8
            ));
        }
        Op::FpToIntFixed { rd, rn, unsigned, src_is64, dest_is64, fbits } => {
            let get = if src_is64 { "ew_dget" } else { "ew_sget" };
            out.push_str(&format!(
                "    /* 0x{a:x}: fixed-point fcvtz{}, #{fbits} */\n    {{ ew_u64 r_ = ew_fp_to_int(ldexp((double){get}(cpu, {rn}), {fbits}), {}, {}, {});\n      {} }}\n",
                if unsigned { "u" } else { "s" },
                FpRound::Zero.c_code(),
                dest_is64 as u8,
                unsigned as u8,
                reg_write(rd, false, "r_")
            ));
        }
        Op::FpRoundFp { rd, rn, round, is64 } => {
            let width = if is64 { "d" } else { "s" };
            let lib = if is64 { "" } else { "f" };
            let (get, set) = if is64 { ("ew_dget", "ew_dset") } else { ("ew_sget", "ew_sset") };
            let call = match round {
                FpRound::NearestEven => "rint",
                FpRound::NearestAway => "round",
                FpRound::PlusInf => "ceil",
                FpRound::MinusInf => "floor",
                FpRound::Zero => "trunc",
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {} {width}{rd}, {width}{rn} */\n    {set}(cpu, {rd}, {call}{lib}({get}(cpu, {rn})));\n",
                fp_round_fp_name(round, is64)
            ));
        }
        Op::FpMovImm { rd, imm8, is64 } => {
            let bytes = if is64 { 8 } else { 4 };
            out.push_str(&format!(
                "    /* 0x{a:x}: fmov {}{rd}, #0x{imm8:02x} */\n    ew_vset(cpu, {rd}, {bytes}, ew_fmov_imm(0x{imm8:02x}, {}));\n",
                if is64 { "d" } else { "s" },
                if is64 { 1 } else { 0 }
            ));
        }
        Op::FpMulAdd { rd, rn, rm, ra, negate_product, negate_addend, is64 } => {
            let width = if is64 { "d" } else { "s" };
            let ty = if is64 { "double" } else { "float" };
            let (get, set) = if is64 { ("ew_dget", "ew_dset") } else { ("ew_sget", "ew_sset") };
            let mnemonic = match (negate_product, negate_addend) {
                (false, false) => "fmadd",
                (false, true) => "fmsub",
                (true, false) => "fnmadd",
                (true, true) => "fnmsub",
            };
            out.push_str(&format!(
                "    /* 0x{a:x}: {mnemonic} {width}{rd}, {width}{rn}, {width}{rm}, {width}{ra} */\n    {{ {ty} p_ = {get}(cpu, {rn}) * {get}(cpu, {rm});\n      if ({}) p_ = -p_;\n      {set}(cpu, {rd}, p_ + ({})); }}\n",
                if negate_product { 1 } else { 0 },
                if negate_addend {
                    format!("-{get}(cpu, {ra})")
                } else {
                    format!("{get}(cpu, {ra})")
                }
            ));
        }
        Op::LoadLiteral { rt, target, is64 } => {
            let bytes = if is64 { 8 } else { 4 };
            out.push_str(&format!(
                "    /* 0x{a:x}: ldr x{rt}, =0x{target:x} */\n    {{ ew_u64 v_ = ew_load(cpu, 0x{target:x}ULL, {bytes}); {} }}\n",
                reg_write(rt, false, &masked(is64, "v_"))
            ));
        }
        Op::Simd(..) | Op::SimdMem(..) => out.push_str(&emit_simd_insn(a, &insn.op)),
        Op::Exclusive { .. } | Op::Cas { .. } => out.push_str(&emit_exclusive(a, &insn.op)),
        Op::Extr { rd, rn, rm, lsb, is64 } => {
            let expr = if is64 {
                if lsb == 0 {
                    reg_read(rm, false)
                } else {
                    format!("(({} >> {lsb}) | ({} << {}))", reg_read(rm, false), reg_read(rn, false), 64 - lsb as u32)
                }
            } else {
                format!(
                    "(((((EW_M32({})) << 32) | EW_M32({})) >> {lsb}) & 0xFFFFFFFFULL)",
                    reg_read(rn, false),
                    reg_read(rm, false)
                )
            };
            out.push_str(&format!("    /* 0x{a:x}: extr */
    {}
", reg_write(rd, false, &expr)));
        }
        Op::MulHigh { rd, rn, rm, unsigned } => {
            let f = if unsigned { "ew_umulh" } else { "ew_smulh" };
            out.push_str(&format!(
                "    /* 0x{a:x}: {}mulh */
    {}
",
                if unsigned { "u" } else { "s" },
                reg_write(rd, false, &format!("{f}({}, {})", reg_read(rn, false), reg_read(rm, false)))
            ));
        }
        Op::Mrs { rt, reg } => {
            out.push_str(&format!(
                "    /* 0x{a:x}: mrs */\n    {{ ew_u64 ew_t0 = 0;\n    if (!ew_mrs(cpu, 0x{a:x}ULL, {reg}u, &ew_t0)) return 0;\n    {} }}\n",
                reg_write(rt, false, "ew_t0")
            ));
        }
        Op::Msr { rt, reg } => {
            out.push_str(&format!(
                "    /* 0x{a:x}: msr */\n    if (!ew_msr(cpu, 0x{a:x}ULL, {reg}u, {})) return 0;\n",
                reg_read(rt, false)
            ));
        }
        Op::Svc { imm } => {
            // Control returns to the run loop, which services the call and
            // resumes at the next instruction.
            out.push_str(&format!(
                "    /* 0x{a:x}: svc */\n    cpu->svc = {imm};\n    cpu->pc = 0x{next:x}ULL;\n    return 0;\n",
                next = a + 4
            ));
        }
        Op::Unsupported { word } | Op::UnsupportedBitfield { word } => {
            out.push_str(&format!(
                "    /* 0x{a:x}: UNSUPPORTED 0x{word:08x} */\n    ew_halt(cpu, 0x{a:x}ULL, \"unsupported instruction 0x{word:08x}\");\n    return 0;\n"
            ));
        }
    }

}

