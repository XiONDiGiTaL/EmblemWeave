/// Emit one translation unit containing every lifted function.
pub fn emit_module(module: &str, funcs: &[LiftedFunction]) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "/* {module}_lift.c - machine-generated by ew-lift {} - do not edit.\n\
         *\n\
         * Every function returns 1 to continue dispatch and 0 after a trap.\n\
         * Blocks: {}, instructions: {}\n\
         */\n\n#include \"ew_aarch64.h\"\n#include \"ew_dispatch.h\"\n\n",
        env!("CARGO_PKG_VERSION"),
        funcs.iter().map(|f| f.blocks.len()).sum::<usize>(),
        funcs.iter().map(|f| f.insn_count()).sum::<usize>()
    ));

    for f in funcs {
        out.push_str(&format!(
            "/* guest 0x{:x}: {} block(s), {} instruction(s), {}, {} jump table(s) */\nint {}(Cpu *cpu)\n{{\n    /* Entered at cpu->pc: 0x{:x} or any block below it. */\n    for (;;) {{\n        switch (cpu->pc) {{\n",
            f.addr,
            f.blocks.len(),
            f.insn_count(),
            if f.complete { "complete" } else { "partial" },
            f.jump_tables,
            f.c_name(),
            f.addr
        ));
        for e in entry_points(f) {
            out.push_str(&format!("        case 0x{e:x}ULL: goto L_{e:x};\n"));
        }
        out.push_str("        default: return 1; /* pc left this function */\n        }\n");

        for b in &f.blocks {
            // Each stretch of a block up to a call, and from a call's return
            // to the next, gets a label and charges its instructions to the
            // budget first: a function that runs out of budget leaves with pc
            // at a point it can be entered at again, and a call returns
            // straight into the code after it.
            let mut seg_start = 0usize;
            for (i, insn) in b.insns.iter().enumerate() {
                if i == seg_start {
                    let n = b.insns[i..].iter().position(|x| is_call(&x.op)).map_or(b.insns.len() - i, |k| k + 1);
                    out.push_str(&format!(
                        "    L_{a:x}:\n    if ((cpu->budget -= {n}) < 0) {{ cpu->budget += {n}; cpu->pc = 0x{a:x}ULL; cpu->svc = -2; return 1; }}\n",
                        a = insn.addr
                    ));
                }
                emit_insn(&mut out, insn, f, b.jump_table.as_ref());
                if is_call(&insn.op) {
                    seg_start = i + 1;
                }
            }
            let conditional = b.insns.last().map(|i| i.op.is_conditional_branch()).unwrap_or(false);
            if conditional {
                // Not taken: continue at the instruction after the branch.
                match b.fallthrough() {
                    Some(ft) => out.push_str(&format!("    cpu->pc = 0x{ft:x}ULL; continue;\n")),
                    None => out.push_str("    return 1;\n"),
                }
            } else if !b.terminated {
                out.push_str(&format!(
                    "    ew_halt(cpu, 0x{:x}ULL, \"block ended before a terminator\");\n    return 0;\n",
                    b.end_addr()
                ));
            }
        }
        out.push_str("    }\n}\n\n");
    }

    // Dispatch table: the runtime only needs the address -> function mapping.
    out.push_str(&format!(
        "const ew_func_entry {module}_functions[] = {{\n"
    ));
    for f in funcs {
        out.push_str(&format!("    {{ 0x{:x}ULL, {} }},\n", f.addr, f.c_name()));
    }
    out.push_str("    { 0ULL, 0 }\n};\n");
    out.push_str(&format!(
        "const unsigned {module}_function_count = {}u;\n",
        funcs.len()
    ));
    // Every block start, so the run loop can enter a function where a call
    // returns or a branch lands, not only at its entry.
    out.push_str(&format!("const ew_func_entry {module}_blocks[] = {{\n"));
    let mut blocks = 0usize;
    for f in funcs {
        for e in entry_points(f) {
            out.push_str(&format!("    {{ 0x{e:x}ULL, {} }},\n", f.c_name()));
            blocks += 1;
        }
    }
    out.push_str("    { 0ULL, 0 }\n};\n");
    out.push_str(&format!("const unsigned {module}_block_count = {blocks}u;\n"));
    out
}

fn is_call(op: &Op) -> bool {
    matches!(op, Op::Bl { .. } | Op::Blr { .. })
}

/// Where a lifted function can be entered: each block start, and the
/// instruction after each call inside a block (where the call returns).
pub fn entry_points(f: &LiftedFunction) -> Vec<u64> {
    let mut v = Vec::new();
    for b in &f.blocks {
        v.push(b.addr);
        for (i, insn) in b.insns.iter().enumerate() {
            if is_call(&insn.op) && i + 1 < b.insns.len() {
                v.push(b.insns[i + 1].addr);
            }
        }
    }
    v.sort_unstable();
    v.dedup();
    v
}

/// Guest memory and state setup shared by every generated harness. The layout
/// matches `interpreter::State::patterned` exactly, so a differential run is
/// comparing instruction semantics rather than test rigs.
pub const HARNESS_SUPPORT: &str = r#"
#define EW_GUEST_SIZE (2u * 1024u * 1024u)
static ew_u8  ew_guest[EW_GUEST_SIZE];
static int    ew_faults;

static ew_u64 ew_mem_read(void *ctx, ew_u64 addr, unsigned bytes)
{
    unsigned i;
    ew_u64 v = 0;
    (void)ctx;
    if (addr + (ew_u64)bytes > (ew_u64)EW_GUEST_SIZE) { ew_faults++; return 0; }
    for (i = 0; i < bytes; i++)
        v |= ((ew_u64)ew_guest[addr + i]) << (8 * i);
    return v;
}

static void ew_mem_write(void *ctx, ew_u64 addr, ew_u64 value, unsigned bytes)
{
    unsigned i;
    (void)ctx;
    if (addr + (ew_u64)bytes > (ew_u64)EW_GUEST_SIZE) { ew_faults++; return; }
    for (i = 0; i < bytes; i++)
        ew_guest[addr + i] = (ew_u8)((value >> (8 * i)) & 0xFFu);
}

static void ew_reset(Cpu *cpu)
{
    int i;
    memset(cpu, 0, sizeof *cpu);
    memset(ew_guest, 0, sizeof ew_guest);
    ew_faults = 0;
    for (i = 0; i < 31; i++) cpu->x[i] = 0x1000ULL + (ew_u64)i * 0x20ULL;
    for (i = 0; i < 32; i++) {
        cpu->v[i][0] = 0x2000ULL + (ew_u64)i * 0x10ULL;
        cpu->v[i][1] = 0x3000ULL + (ew_u64)i * 0x10ULL;
    }
    cpu->sp = 0x100000ULL;
    cpu->budget = (ew_i64)1 << 60;
    cpu->mem_read = ew_mem_read;
    cpu->mem_write = ew_mem_write;
}

static void ew_report(Cpu *cpu, ew_u64 base)
{
    int i;
    printf("fn=0x%llx halted=%d pc=%llx nzcv=%x",
           (unsigned long long)base, cpu->halted ? 1 : 0,
           (unsigned long long)cpu->pc, cpu->nzcv);
    /* Every register is printed, not a sample: a wrong lane or a stale upper
     * half is exactly the kind of bug a partial comparison hides. */
    for (i = 0; i < 31; i++)
        printf(" x%d=%llx", i, (unsigned long long)cpu->x[i]);
    printf(" sp=%llx", (unsigned long long)cpu->sp);
    for (i = 0; i < 32; i++)
        printf(" v%d=%llx:%llx", i, (unsigned long long)cpu->v[i][1],
               (unsigned long long)cpu->v[i][0]);
    printf("\n");
}
"#;

/// Emit a self-checking harness that runs one lifted function on the shared
/// register pattern and prints the resulting state.
pub fn emit_harness(module: &str, func: &LiftedFunction) -> String {
    let _ = module;
    format!(
        r#"/* generated harness: executes one lifted guest function */
#include "ew_aarch64.h"
{HARNESS_SUPPORT}
int {}(Cpu *cpu);

int main(void)
{{
    Cpu cpu;
    ew_reset(&cpu);
    cpu.pc = 0x{:x}ULL;
    (void){}(&cpu);
    ew_report(&cpu, 0x{:x}ULL);
    if (ew_faults) printf("guest-memory-faults=%d\n", ew_faults);
    return cpu.halted ? 2 : 0;
}}
"#,
        func.c_name(),
        func.addr,
        func.c_name(),
        func.addr
    )
}

/// Emit a program that runs many lifted functions in sequence. One compile and
/// one run then covers a whole differential campaign.
pub fn emit_campaign(module: &str, funcs: &[LiftedFunction]) -> String {
    let mut out = emit_module(module, funcs);
    out.push_str(HARNESS_SUPPORT);
    out.push_str("\nint main(void)\n{\n    Cpu cpu;\n");
    for f in funcs {
        out.push_str(&format!(
            "    ew_reset(&cpu);\n    cpu.pc = 0x{:x}ULL;\n    (void){}(&cpu);\n    ew_report(&cpu, 0x{:x}ULL);\n",
            f.addr,
            f.c_name(),
            f.addr
        ));
    }
    out.push_str("    if (ew_faults) printf(\"guest-memory-faults=%d\\n\", ew_faults);\n    return 0;\n}\n");
    out
}

