//! C emission for lifted AArch64 functions.
//!
//! The generated code is intentionally boring: one statement per guest
//! instruction, an explicit guest stack pointer, and a return to the dispatcher
//! at every control-flow edge. That keeps the translation auditable, which
//! matters far more than dispatch speed at this stage. Unsupported instructions
//! become `ew_halt()` calls with the guest address, never a silent guess.

use crate::aarch64::{DataOp2, FpBinop, FpRound, FpUnop, LogicalOp, MemMode, Op, Shift};
use crate::scan::{Insn, LiftedFunction};

/// Support header emitted next to every generated translation unit.
pub const RUNTIME_HEADER: &str = concat!(r#"/* ew_aarch64.h — generated by ew-lift. Shared by lifted code and the runtime.
 *
 * Guest registers are explicit so translations stay readable and auditable.
 * x31 is context dependent (XZR or SP), which the EW_R/EW_W macros encode.
 */
#ifndef EW_AARCH64_H
#define EW_AARCH64_H

#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <math.h>

typedef uint64_t ew_u64;
typedef int64_t  ew_i64;
typedef uint32_t ew_u32;
typedef int32_t  ew_i32;
typedef uint8_t  ew_u8;

typedef struct Cpu {
    ew_u64 x[31];          /* x0..x30 */
    ew_u64 v[32][2];       /* V0..V31: [0] low eight bytes, [1] high eight */
    ew_u64 sp;
    ew_u64 pc;
    ew_u32 nzcv;           /* bit3=N bit2=Z bit1=C bit0=V */
    int    halted;
    char   halt_reason[128];
    ew_u64 tpidrro;        /* thread pointers */
    ew_u64 tpidr;
    ew_u64 fpcr;
    ew_u64 fpsr;
    ew_u64 (*counter)(void); /* system counter, 19.2 MHz; NULL: none */
    int    svc;            /* pending supervisor call number, -1 when none, -2 out of budget */
    ew_u64 excl_addr;      /* exclusive monitor: reserved address */
    int    excl_valid;     /* and whether a reservation is held */
    /* Guest memory access. Supplied by the runtime; the harness may stub it. */
    ew_u64 (*mem_read)(void *ctx, ew_u64 addr, unsigned bytes);
    void   (*mem_write)(void *ctx, ew_u64 addr, ew_u64 value, unsigned bytes);
    void   *mem_ctx;
    /* Native runs: guest memory as one host block (guest address = offset),
     * read and written directly; NULL sends every access to the callbacks. */
    ew_u8  *mem_base;
    ew_u64 mem_size;
    /* Instructions left before the function returns to the run loop, checked
     * at every block so a long loop still lets other guest threads run. */
    ew_i64 budget;
} Cpu;

/* The index expression clamps 31 to 0 so the unused branch of these ternaries
 * never forms an out-of-bounds access at compile time. */
#define EW_IDX(i) (((i) == 31) ? 0 : (i))
#define EW_R(cpu, i, spok)                                                     \
    (((i) == 31) ? (((spok) && (i) == 31) ? (cpu)->sp : 0ULL) : (cpu)->x[EW_IDX(i)])
#define EW_W(cpu, i, spok, v)                                                  \
    do {                                                                       \
        ew_u64 ew_v_ = (v);                                                    \
        if ((i) == 31) {                                                       \
            if (spok) { (cpu)->sp = ew_v_; }                                   \
        } else {                                                               \
            (cpu)->x[EW_IDX(i)] = ew_v_;                                       \
        }                                                                      \
    } while (0)

#define EW_M32(v) ((ew_u64)(ew_u32)(v))
#define EW_M(cpu_is64, v) ((cpu_is64) ? (ew_u64)(v) : EW_M32(v))

static inline void ew_halt(Cpu *cpu, ew_u64 pc, const char *why)
{
    cpu->halted = 1;
    cpu->pc = pc;
    snprintf(cpu->halt_reason, sizeof(cpu->halt_reason), "pc=0x%llx %s",
             (unsigned long long)pc, why);
}

/* System registers, numbered by the 15-bit field of mrs/msr. Values match the
 * interpreter's read_sysreg. */
static inline int ew_mrs(Cpu *cpu, ew_u64 pc, ew_u32 reg, ew_u64 *out)
{
    switch (reg) {
    case 0x5E83: *out = cpu->tpidrro; return 1;          /* tpidrro_el0 */
    case 0x5E82: *out = cpu->tpidr; return 1;            /* tpidr_el0 */
    case 0x5F01: case 0x5F02:                            /* cntpct, cntvct */
        *out = cpu->counter ? cpu->counter() : 0; return 1;
    case 0x5F00: *out = 19200000ULL; return 1;           /* cntfrq_el0 */
    case 0x5A20: *out = cpu->fpcr; return 1;
    case 0x5A21: *out = cpu->fpsr; return 1;
    case 0x5A10: *out = (ew_u64)cpu->nzcv << 28; return 1;
    case 0x5801: *out = 0x8444C004ULL; return 1;         /* ctr_el0 */
    case 0x5807: *out = 4; return 1;                     /* dczid_el0 */
    default: ew_halt(cpu, pc, "mrs from a system register that is not modelled"); return 0;
    }
}

static inline int ew_msr(Cpu *cpu, ew_u64 pc, ew_u32 reg, ew_u64 v)
{
    switch (reg) {
    case 0x5E82: cpu->tpidr = v; return 1;
    case 0x5A20: cpu->fpcr = v; return 1;
    case 0x5A21: cpu->fpsr = v; return 1;
    case 0x5A10: cpu->nzcv = (ew_u32)((v >> 28) & 0xF); return 1;
    default: ew_halt(cpu, pc, "msr to a system register that is not modelled"); return 0;
    }
}

/* Vector register access. Writing a scalar width zeroes the upper bytes, which
 * is the architectural rule for every SIMD/FP and V-register write. */
static inline ew_u64 ew_vget(Cpu *cpu, unsigned i, unsigned bytes)
{
    ew_u64 lo = cpu->v[i & 31u][0];
    ew_u64 keep = (bytes >= 8u) ? ~(ew_u64)0 : (((ew_u64)1 << (bytes * 8u)) - 1u);
    return lo & keep;
}

static inline void ew_vset(Cpu *cpu, unsigned i, unsigned bytes, ew_u64 value)
{
    unsigned idx = i & 31u;
    ew_u64 keep = (bytes >= 8u) ? ~(ew_u64)0 : (((ew_u64)1 << (bytes * 8u)) - 1u);
    cpu->v[idx][0] = value & keep;
    cpu->v[idx][1] = 0;
}

static inline void ew_vset128(Cpu *cpu, unsigned i, ew_u64 lo, ew_u64 hi)
{
    unsigned idx = i & 31u;
    cpu->v[idx][0] = lo;
    cpu->v[idx][1] = hi;
}

static inline ew_u64 ew_load(Cpu *cpu, ew_u64 addr, unsigned bytes)
{
    if (cpu->mem_base && addr <= cpu->mem_size && bytes <= cpu->mem_size - addr) {
        ew_u64 v = 0;
        memcpy(&v, cpu->mem_base + addr, bytes); /* the host is little endian */
        return v;
    }
    return cpu->mem_read(cpu->mem_ctx, addr, bytes);
}

static inline void ew_store(Cpu *cpu, ew_u64 addr, ew_u64 value, unsigned bytes)
{
    if (cpu->mem_base && addr <= cpu->mem_size && bytes <= cpu->mem_size - addr) {
        memcpy(cpu->mem_base + addr, &value, bytes);
        return;
    }
    cpu->mem_write(cpu->mem_ctx, addr, value, bytes);
}

static inline void ew_flags_nz(Cpu *cpu, ew_u64 v, int is64)
{
    ew_u32 n = is64 ? (ew_u32)(v >> 63) : (ew_u32)((v >> 31) & 1);
    ew_u32 z = (v == 0) ? 1u : 0u;
    cpu->nzcv = (n << 3) | (z << 2); /* logical ops clear C and V */
}

static inline void ew_flags_add(Cpu *cpu, ew_u64 a, ew_u64 b, ew_u64 r, int is64)
{
    ew_u32 c, v, n, z;
    if (is64) {
        c = (r < a);
        v = (ew_u32)((((a ^ r) & (b ^ r)) >> 63) & 1);
        n = (ew_u32)(r >> 63);
        z = (r == 0);
    } else {
        ew_u32 a32 = (ew_u32)a, b32 = (ew_u32)b, r32 = (ew_u32)r;
        c = (r32 < a32);
        v = ((a32 ^ r32) & (b32 ^ r32)) >> 31;
        n = r32 >> 31;
        z = (r32 == 0);
    }
    cpu->nzcv = (n << 3) | (z << 2) | (c << 1) | v;
}

static inline void ew_flags_sub(Cpu *cpu, ew_u64 a, ew_u64 b, ew_u64 r, int is64)
{
    ew_u32 c, v, n, z;
    if (is64) {
        c = (a >= b);
        v = (ew_u32)((((a ^ b) & (a ^ r)) >> 63) & 1);
        n = (ew_u32)(r >> 63);
        z = (r == 0);
    } else {
        ew_u32 a32 = (ew_u32)a, b32 = (ew_u32)b, r32 = (ew_u32)r;
        c = (a32 >= b32);
        v = ((a32 ^ b32) & (a32 ^ r32)) >> 31;
        n = r32 >> 31;
        z = (r32 == 0);
    }
    cpu->nzcv = (n << 3) | (z << 2) | (c << 1) | v;
}

static inline ew_u64 ew_shift(ew_u64 v, unsigned kind, unsigned amount, int is64)
{
    unsigned width = is64 ? 64u : 32u;
    amount %= width;
    v = is64 ? v : EW_M32(v);
    switch (kind) {
    case 0: return EW_M(is64, v << amount);
    case 1: return EW_M(is64, v >> amount);
    case 2: return is64 ? (ew_u64)((ew_i64)v >> amount)
                        : EW_M32((ew_u32)((int32_t)(ew_u32)v >> amount));
    default:
        return is64 ? (v >> amount) | (v << ((width - amount) % width))
                    : EW_M32(((ew_u32)v >> amount) | ((ew_u32)v << ((width - amount) % width)));
    }
}

static inline ew_u64 ew_ones(unsigned n)
{
    return (n >= 64u) ? ~(ew_u64)0 : ((((ew_u64)1) << n) - 1u);
}

/* Operand extension, matching the AArch64 `option` field. */
static inline ew_u64 ew_extend(ew_u64 v, unsigned option)
{
    switch (option & 7u) {
    case 0: return (ew_u64)(ew_u8)v;
    case 1: return (ew_u64)(uint16_t)v;
    case 2: return (ew_u64)(ew_u32)v;
    case 3: return v;
    case 4: return (ew_u64)(ew_i64)(int8_t)v;
    case 5: return (ew_u64)(ew_i64)(int16_t)v;
    case 6: return (ew_u64)(ew_i64)(int32_t)(ew_u32)v;
    default: return v;
    }
}

static inline ew_u64 ew_rbit(ew_u64 v, int is64)
{
    ew_u64 r = 0;
    unsigned bits = is64 ? 64u : 32u;
    unsigned i;
    for (i = 0; i < bits; i++) {
        if ((v >> i) & 1u) r |= (ew_u64)1 << (bits - 1u - i);
    }
    return is64 ? r : EW_M32(r);
}

/* Reverse the byte order inside each `group`-byte unit. */
static inline ew_u64 ew_rev_within(ew_u64 v, unsigned group, int is64)
{
    unsigned bits = is64 ? 64u : 32u;
    unsigned base = 0;
    ew_u64 out = 0;
    while (base < bits) {
        unsigned j;
        for (j = 0; j < group; j++) {
            ew_u64 byte = (v >> (base + j * 8u)) & 0xFFu;
            out |= byte << (base + (group - 1u - j) * 8u);
        }
        base += group * 8u;
    }
    return is64 ? out : EW_M32(out);
}

static inline ew_u64 ew_clz(ew_u64 v, int is64)
{
    unsigned bits = is64 ? 64u : 32u;
    unsigned n = 0;
    ew_u64 x = is64 ? v : EW_M32(v);
    while (n < bits && ((x >> (bits - 1u - n)) & 1u) == 0) n++;
    return n;
}

/* CLS counts the leading bits equal to the sign bit, minus one. */
static inline ew_u64 ew_cls(ew_u64 v, int is64)
{
    ew_u64 x = is64 ? (v ^ (ew_u64)((ew_i64)v >> 1))
                    : EW_M32((ew_u32)v ^ (ew_u32)((int32_t)(ew_u32)v >> 1));
    ew_u64 z = ew_clz(x, is64);
    return z > 0 ? z - 1u : 0u;
}

/* Sign-extend a value whose sign bit is at `top` inside a 32/64-bit result. */
static inline ew_u64 ew_sext(ew_u64 v, unsigned top, int is64)
{
    unsigned s = 63u - (top & 63u);
    ew_u64 r = (ew_u64)((ew_i64)(v << s) >> s);
    return is64 ? r : EW_M32(r);
}

/* sbfm / bfm / ubfm, which also cover sbfx, ubfx, sbfiz, ubfiz, bfi, bfxil,
 * lsl, lsr and asr with an immediate. opc: 0 sbfm, 1 bfm, 2 ubfm. */
static inline ew_u64 ew_bitfield(ew_u64 src, ew_u64 dst, unsigned immr,
                                 unsigned imms, unsigned opc, int is64)
{
    unsigned bits = is64 ? 64u : 32u;
    unsigned width, shift;
    ew_u64 field, result;

    if ((immr & (bits - 1u)) <= (imms & (bits - 1u))) {
        /* extracting: the field moves down to bit 0 */
        width = (imms & (bits - 1u)) - (immr & (bits - 1u)) + 1u;
        shift = 0u;
        field = (src >> (immr & (bits - 1u))) & ew_ones(width);
    } else {
        /* inserting: the field wraps and moves up */
        width = (imms & (bits - 1u)) + 1u;
        shift = bits - (immr & (bits - 1u));
        field = (src & ew_ones(width)) << shift;
    }

    if (opc == 2u) {
        result = EW_M(is64, field);
    } else if (opc == 0u) {
        result = ew_sext(field, shift + width - 1u, is64);
    } else {
        ew_u64 mask = ew_ones(width) << shift;
        result = EW_M(is64, (dst & ~mask) | field);
    }
    return result;
}

/* udiv/sdiv trap nothing: division by zero yields zero, and the signed
 * overflow case wraps, matching AArch64 rather than the C undefined cases. */
static inline ew_u64 ew_udiv(ew_u64 a, ew_u64 b)
{
    return b ? a / b : 0u;
}

static inline ew_u64 ew_sdiv(ew_u64 a, ew_u64 b, int is64)
{
    if (!b) return 0u;
    if (is64) {
        if (a == 0x8000000000000000ULL && b == ~(ew_u64)0) return a;
        return (ew_u64)((ew_i64)a / (ew_i64)b);
    }
    {
        ew_u32 a32 = (ew_u32)a, b32 = (ew_u32)b;
        if (a32 == 0x80000000u && b32 == 0xFFFFFFFFu) return EW_M32(a32);
        return EW_M32((ew_u32)((int32_t)a32 / (int32_t)b32));
    }
}

/* crc32b/h/w/x and crc32cb/h/w/x. The checksum is CRC-32 with no pre- or
 * post-inversion, continuing from the value in the first operand and absorbing
 * `bytes` bytes of the second from its low end. `poly` is the reflected
 * polynomial: 0xEDB88320 for the IEEE form, 0x82F63B78 for Castagnoli. */
static inline ew_u64 ew_crc32(ew_u64 crc, ew_u64 data, unsigned bytes, ew_u32 poly)
{
    ew_u32 c = (ew_u32)crc;
    unsigned i, b;
    for (i = 0; i < bytes; i++) {
        c ^= (ew_u32)(data & 0xFFu);
        for (b = 0; b < 8; b++) {
            c = (c & 1u) ? ((c >> 1) ^ poly) : (c >> 1);
        }
        data >>= 8;
    }
    return EW_M32(c);
}

static inline int ew_cond(Cpu *cpu, unsigned cond);

/* csel/csinc/csinv/csneg: kind 1..4 selects the "else" operand form. */
static inline ew_u64 ew_condsel(Cpu *cpu, unsigned cond, ew_u64 a, ew_u64 b,
                                unsigned kind, int is64)
{
    ew_u64 r;
    if (ew_cond(cpu, cond)) {
        r = a;
    } else {
        switch (kind) {
        case 1:  r = b; break;
        case 2:  r = b + 1; break;
        case 3:  r = ~b; break;
        default: r = (ew_u64)(0 - b); break;
        }
    }
    return is64 ? r : EW_M32(r);
}

static inline int ew_cond(Cpu *cpu, unsigned cond)
{
    ew_u32 n = (cpu->nzcv >> 3) & 1, z = (cpu->nzcv >> 2) & 1;
    ew_u32 c = (cpu->nzcv >> 1) & 1, v = cpu->nzcv & 1;
    switch (cond) {
    case 0:  return (int)z;
    case 1:  return !z;
    case 2:  return (int)c;
    case 3:  return !c;
    case 4:  return (int)n;
    case 5:  return !n;
    case 6:  return (int)v;
    case 7:  return !v;
    case 8:  return c && !z;
    case 9:  return !c || z;
    case 10: return n == v;
    case 11: return n != v;
    case 12: return !z && (n == v);
    case 13: return z || (n != v);
    default: return 1;
    }
}

/* Scalar floating point. Values move as bit patterns in both directions, so
 * signed zeros, denormals and NaN payloads survive unchanged. */
static inline float ew_sget(Cpu *cpu, unsigned i)
{
    ew_u32 bits = (ew_u32)(cpu->v[i & 31u][0] & 0xFFFFFFFFu);
    float f;
    memcpy(&f, &bits, sizeof f);
    return f;
}

static inline void ew_sset(Cpu *cpu, unsigned i, float f)
{
    ew_u32 bits;
    memcpy(&bits, &f, sizeof bits);
    ew_vset(cpu, i, 4, bits);
}

static inline double ew_dget(Cpu *cpu, unsigned i)
{
    ew_u64 bits = cpu->v[i & 31u][0];
    double d;
    memcpy(&d, &bits, sizeof d);
    return d;
}

static inline void ew_dset(Cpu *cpu, unsigned i, double d)
{
    ew_u64 bits;
    memcpy(&bits, &d, sizeof bits);
    ew_vset(cpu, i, 8, bits);
}

/* fmax and fmin with the architectural NaN rule: one NaN loses to the number,
 * and the two signed zeros keep a fixed sign instead of comparing equal. */
static inline float ew_fmax32(float a, float b)
{
    if (a != a) return b;
    if (b != b) return a;
    if (a == b) return (a == 0.0f && signbit(a) != signbit(b)) ? 0.0f : a;
    return a > b ? a : b;
}

static inline float ew_fmin32(float a, float b)
{
    if (a != a) return b;
    if (b != b) return a;
    if (a == b) return (a == 0.0f && signbit(a) != signbit(b)) ? -0.0f : a;
    return a < b ? a : b;
}

static inline double ew_fmax64(double a, double b)
{
    if (a != a) return b;
    if (b != b) return a;
    if (a == b) return (a == 0.0 && signbit(a) != signbit(b)) ? 0.0 : a;
    return a > b ? a : b;
}

static inline double ew_fmin64(double a, double b)
{
    if (a != a) return b;
    if (b != b) return a;
    if (a == b) return (a == 0.0 && signbit(a) != signbit(b)) ? -0.0 : a;
    return a < b ? a : b;
}

/* FP compare writes NZCV exactly as the architecture does: unordered sets C
 * and V, equal sets Z and C, less than sets N and greater sets C. */
static inline void ew_fp_flags(Cpu *cpu, int unordered, int eq, int lt, int gt)
{
    if (unordered) cpu->nzcv = 0x3u;
    else if (eq)    cpu->nzcv = 0x6u;
    else if (lt)    cpu->nzcv = 0x8u;
    else if (gt)    cpu->nzcv = 0x2u;
}

/* mode: 0 nearest even, 1 nearest away, 2 toward +inf, 3 toward -inf, 4 zero */
static inline double ew_round_mode(double v, unsigned mode)
{
    switch (mode) {
    case 0:  return rint(v);
    case 1:  return round(v);
    case 2:  return ceil(v);
    case 3:  return floor(v);
    default: return trunc(v);
    }
}

/* Float to integer with architectural saturation: NaN becomes zero and an out
 * of range value clamps, because a C cast out of range is undefined. */
static inline ew_u64 ew_fp_to_int(double v, unsigned mode, int is64, int uns)
{
    double r;
    if (v != v) return 0;
    r = ew_round_mode(v, mode);
    if (uns) {
        double limit = is64 ? 18446744073709551616.0 : 4294967296.0;
        if (r <= 0.0) return 0;
        if (r >= limit) return is64 ? ~(ew_u64)0 : (ew_u64)0xFFFFFFFFu;
        return (ew_u64)r;
    }
    if (is64) {
        if (r >= 9223372036854775808.0) return (ew_u64)0x7FFFFFFFFFFFFFFFull;
        if (r <= -9223372036854775808.0) return (ew_u64)0x8000000000000000ull;
        return (ew_u64)(ew_i64)r;
    }
    if (r >= 2147483648.0) return (ew_u64)0x7FFFFFFFu;
    if (r <= -2147483648.0) return (ew_u64)0x80000000u;
    return (ew_u64)(ew_u32)(ew_i32)r;
}

/* Fixed-point integer to floating point: the integer scaled by 2^-fbits. */
static inline ew_u64 ew_int_to_fp_fixed(ew_u64 raw, int src_is64, int uns, int dest_is64, int fbits)
{
    double v;
    if (src_is64) {
        v = uns ? (double)raw : (double)(ew_i64)raw;
    } else {
        v = uns ? (double)(ew_u32)raw : (double)(ew_i32)(ew_u32)raw;
    }
    v = ldexp(v, -fbits);
    if (dest_is64) {
        ew_u64 bits;
        memcpy(&bits, &v, sizeof bits);
        return bits;
    } else {
        float f = (float)v;
        ew_u32 bits;
        memcpy(&bits, &f, sizeof bits);
        return bits;
    }
}

/* Integer to floating point, returning the destination bit pattern. */
static inline ew_u64 ew_int_to_fp(ew_u64 raw, int src_is64, int uns, int dest_is64)
{
    double v;
    if (src_is64) {
        v = uns ? (double)raw : (double)(ew_i64)raw;
    } else {
        v = uns ? (double)(ew_u32)raw : (double)(ew_i32)(ew_u32)raw;
    }
    if (dest_is64) {
        ew_u64 bits;
        memcpy(&bits, &v, sizeof bits);
        return bits;
    } else {
        float f = (float)v;
        ew_u32 bits;
        memcpy(&bits, &f, sizeof bits);
        return bits;
    }
}

/* High half of a 64x64 multiply, built from 32-bit pieces so the emitted C
 * needs no 128-bit integer type (MSVC has none). */
static inline ew_u64 ew_umulh(ew_u64 a, ew_u64 b)
{
    ew_u64 al = a & 0xFFFFFFFFu, ah = a >> 32, bl = b & 0xFFFFFFFFu, bh = b >> 32;
    ew_u64 ll = al * bl, lh = al * bh, hl = ah * bl, hh = ah * bh;
    ew_u64 mid = (ll >> 32) + (lh & 0xFFFFFFFFu) + (hl & 0xFFFFFFFFu);
    return hh + (lh >> 32) + (hl >> 32) + (mid >> 32);
}

static inline ew_u64 ew_smulh(ew_u64 a, ew_u64 b)
{
    ew_u64 h = ew_umulh(a, b);
    if ((ew_i64)a < 0) h -= b;
    if ((ew_i64)b < 0) h -= a;
    return h;
}

/* The fmov immediate is three exponent bits with a bias of three and four
 * fraction bits in sixteenths. */
static inline ew_u64 ew_fmov_imm(unsigned imm8, int is64)
{
    int sign = (int)((imm8 >> 7) & 1u);
    int field = (int)((((imm8 >> 6) ^ 1u) << 2) | ((imm8 >> 4) & 3u));
    double frac = (double)(imm8 & 0xFu) / 16.0;
    double value = (1.0 + frac) * ldexp(1.0, field - 3);
    if (sign) value = -value;
    if (is64) {
        ew_u64 bits;
        memcpy(&bits, &value, sizeof bits);
        return bits;
    } else {
        float f = (float)value;
        ew_u32 bits;
        memcpy(&bits, &f, sizeof bits);
        return bits;
    }
}

"#,
    include_str!("ew_simd.h"),
    "
#endif /* EW_AARCH64_H */
"
);

