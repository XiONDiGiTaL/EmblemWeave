#!/usr/bin/env python3
"""Turns probe findings (findings/*.tsv, made by sass_probe.py) into decoder/SassDecoder.Probed.cs."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
names = {}
for ln in open(os.path.join(here, 'findings', 's2r_sr_index.tsv')):
    if ln.startswith('#'): continue
    _, _, v, text = ln.rstrip('\n').split('\t')
    n = text.split(', ', 1)[1]
    if not re.fullmatch(r'SR\d+', n): names[int(v, 16)] = n
cs2r = {}
for ln in open(os.path.join(here, 'findings', 'cs2r_index.tsv')):
    if ln.startswith('#'): continue
    _, _, v, text = ln.rstrip('\n').split('\t')
    n = text.split(', ', 1)[1]
    if not re.fullmatch(r'SR\d+', n): cs2r[int(v, 16)] = n
for k, v in cs2r.items():
    assert names.get(k, v) == v, (k, v)
    names[k] = v
bar = {}
for ln in open(os.path.join(here, 'findings', 'bmov_special_f55.tsv')):
    if ln.startswith('#'): continue
    _, _, v, text = ln.rstrip('\n').split('\t')
    n = text.split(', ', 1)[1]
    if not n.startswith('???'): bar[int(v, 16)] = n
brows = ', '.join(f'"{bar[i]}"' if i in bar else 'null' for i in range(64))
rows = ',\n            '.join(f'"{names[i]}"' if i in names else 'null' for i in range(256))
out = f'''// SPDX-License-Identifier: MIT
// GENERATED by tools/shaders/ampere/probe/gen_tables.py from probe findings (findings/s2r_sr_index.tsv, cs2r_index.tsv, bmov_special_f55.tsv):
// special-register names nvdisasm prints for S2R/S2UR/CS2R index 72..80. Do not edit by hand.
namespace Nx.Shaders.Ampere
{{
    public static partial class SassDecoder
    {{
        internal static readonly string?[] SrNames =
        {{
            {rows}
        }};

        /// BMOV.32 special operands, index 24..30 (findings/bmov_special_f55.tsv)
        internal static readonly string?[] BarSpecialNames = {{ {brows} }};
    }}
}}
'''
open(os.path.join(here, '..', 'decoder', 'SassDecoder.Probed.cs'), 'w', newline='\n').write(out)
print(len(names), 'names')
