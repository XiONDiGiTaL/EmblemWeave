#!/usr/bin/env python3
"""Bit-field probe for Ampere SASS (CuAssembler-style method): take one real instruction word, sweep a field through all
its values (or flip single bits), disassemble every variant with nvdisasm in one call, and print what nvdisasm says.
Findings are data generated by running NVIDIA's disassembler on our own words; nothing is read from nvdisasm's internal tables.

Usage: python -I sass_probe.py sweep <lo-hex> <hi-hex> <start> <len> [--values a-b] [--out f.tsv]
       python -I sass_probe.py flip  <lo-hex> <hi-hex> [--bits a-b] [--out f.tsv]
Bits are numbered 0..127 over the 128-bit word (lo = 0..63, hi = 64..127), as in Mesa NAK sm70_encode.rs.
"""
import argparse, os, re, struct, subprocess, sys, tempfile

NVDISASM = r'C:\Program Files\NVIDIA GPU Computing Toolkit\CUDA\v13.3\bin\nvdisasm.exe'
LINE = re.compile(r'^\s*/\*([0-9a-f]{4,})\*/\s*(.*?)\s*;\s*/\*\s*(0x[0-9a-f]{16})\s*\*/\s*$')


def low_priority():
    if os.name == 'nt':
        import ctypes
        ctypes.windll.kernel32.SetPriorityClass(ctypes.windll.kernel32.GetCurrentProcess(), 0x4000)


def disasm_each(words, sm='SM86'):
    """nvdisasm one variant at a time would be slow; disassemble all in one block and fall back per word on rejection."""
    out = [None] * len(words)
    with tempfile.TemporaryDirectory() as td:
        def run(ws, base):
            p = os.path.join(td, 'p.bin')
            with open(p, 'wb') as f:
                for lo, hi in ws:
                    f.write(struct.pack('<QQ', lo, hi))
            cmd = [NVDISASM, '-b', sm, '-hex'] + (['--base-address', hex(base)] if base else []) + [p]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode != 0 or 'error' in r.stderr:
                return None
            res = []
            for ln in r.stdout.splitlines():
                m = LINE.match(ln)
                if m:
                    res.append(re.sub(r'\s+', ' ', m.group(2)).strip())
            return res if len(res) == len(ws) else None
        whole = run(words, 0)
        if whole:
            return whole
        for i, w in enumerate(words):
            one = run([w], i * 16)
            out[i] = one[0] if one else '<illegal>'
    return out


def setf(lo, hi, start, ln, v):
    w = lo | (hi << 64)
    mask = ((1 << ln) - 1) << start
    w = (w & ~mask) | ((v << start) & mask)
    return w & ((1 << 64) - 1), w >> 64


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('mode', choices=['sweep', 'flip'])
    ap.add_argument('lo'); ap.add_argument('hi')
    ap.add_argument('start', nargs='?', type=int, default=0)
    ap.add_argument('len', nargs='?', type=int, default=1)
    ap.add_argument('--values'); ap.add_argument('--bits', default='0-127'); ap.add_argument('--out')
    a = ap.parse_args()
    low_priority()
    lo, hi = int(a.lo, 16), int(a.hi, 16)
    rows, words = [], []
    if a.mode == 'sweep':
        lo_v, hi_v = (map(int, a.values.split('-')) if a.values else (0, (1 << a.len) - 1))
        for v in range(lo_v, hi_v + 1):
            words.append(setf(lo, hi, a.start, a.len, v)); rows.append(f'{a.start}\t{a.len}\t{v:#x}')
    else:
        b0, b1 = map(int, a.bits.split('-'))
        for b in range(b0, b1 + 1):
            w = (lo | (hi << 64)) ^ (1 << b)
            words.append((w & ((1 << 64) - 1), w >> 64)); rows.append(f'{b}\t1\tflip')
    texts = disasm_each(words)
    lines = [f'# base {lo:#018x} {hi:#018x}  base text: {disasm_each([(lo, hi)])[0]}']
    lines += [f'{r}\t{t}' for r, t in zip(rows, texts)]
    text = '\n'.join(lines) + '\n'
    if a.out:
        open(a.out, 'w', newline='\n').write(text)
    sys.stdout.write(text)


if __name__ == '__main__':
    main()
