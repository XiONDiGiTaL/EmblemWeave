"""Rebuild post_patch_spirv.inc from post_patch_shaders.frag (authored stand-ins, no game data required)."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--glslang', default='glslangValidator')
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    text = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by generate_post_patch_shaders.py from post_patch_shaders.frag.\n'
    with tempfile.TemporaryDirectory() as tmp:
        for name, define in [('kGt3Clamps', 'GT3'), ('kGt2Clamps', 'GT2'), ('kMotionBlurLike', 'MB'), ('kVignetteLike', 'VIG'),
                             ('kOwnPushConstant', 'PC'), ('kTwoBuffers', 'TWO')]:
            output = Path(tmp) / 'shader.spv'
            subprocess.run([args.glslang, '-V', '--target-env', 'vulkan1.3', '-S', 'frag', '-D' + define, str(here / 'post_patch_shaders.frag'),
                            '-o', str(output)], check=True, stdout=subprocess.DEVNULL)
            data = output.read_bytes()
            words = struct.unpack('<%dI' % (len(data) // 4), data)
            text += 'static const uint32_t ' + name + '[] = {\n'
            text += ''.join(', '.join('0x%08x' % x for x in words[i:i + 8]) + ',\n' for i in range(0, len(words), 8))
            text += '};\n'
    (here / 'post_patch_spirv.inc').write_bytes(text.encode())


if __name__ == '__main__':
    main()
