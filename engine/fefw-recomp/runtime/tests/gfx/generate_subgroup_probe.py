"""Rebuild the authored Vulkan subgroup probe (no game data required)."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--glslang', default='glslangValidator')
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    text = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by generate_subgroup_probe.py from the adjacent authored GLSL sources.\n'
    with tempfile.TemporaryDirectory() as tmp:
        for name, source, flags in [
            ('kPortableSubgroupProbe', 'subgroup_portable.comp', []),
            ('kFragmentSubgroupProbe', 'subgroup_portable.comp', ['-S', 'frag', '-DFRAGMENT_PROBE=1']),
            ('kProbeVertex', 'subgroup_probe.vert', []),
        ]:
            output = Path(tmp) / 'probe.spv'
            subprocess.run([args.glslang, '-V', '--target-env', 'vulkan1.1', *flags, str(here/source), '-o', str(output)], check=True)
            data = output.read_bytes()
            words = struct.unpack('<%dI' % (len(data)//4), data)
            text += 'static const uint32_t '+name+'[] = {\n'
            text += ''.join(', '.join('0x%08x' % x for x in words[i:i+8])+',\n' for i in range(0,len(words),8))
            text += '};\n'
    (here/'subgroup_portable_spirv.inc').write_bytes(text.encode())


if __name__ == '__main__':
    main()
