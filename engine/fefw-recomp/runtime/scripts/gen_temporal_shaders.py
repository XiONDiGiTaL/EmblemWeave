# Compiles the temporal upscalers' input pass (motion vectors from depth and the camera, depth and colour copies) with glslc, validates it
# with spirv-val, and writes src/gfx/extras/temporal_shaders.inc (uint32 array). The .inc is committed, so building the runtime does not need
# the SDK.
# Run: python -I scripts/gen_temporal_shaders.py   (exit 1 and no .inc written if the shader fails to compile or validate)
# glslc / spirv-val: the GLSLC and SPIRV_VAL environment variables, else the Vulkan SDK's, else the ones on PATH.
import os, shutil, subprocess, sys, tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = os.path.join(root, "src", "gfx", "extras", "temporal_shaders.inc")


def tool(env, name):
    if os.environ.get(env):
        return os.environ[env]
    sdk = os.path.join(r"C:\VulkanSDK\1.4.363.0\Bin", name + ".exe")
    if os.path.exists(sdk):
        return sdk
    found = shutil.which(name)
    if not found:
        sys.stderr.write("%s not found (set %s)\n" % (name, env))
        sys.exit(1)
    return found


SRC = r"""
#version 450
layout(local_size_x = 8, local_size_y = 8) in;

layout(set = 0, binding = 0) uniform sampler2D u_depth;   // the scene depth (depth aspect), read with texelFetch
layout(set = 0, binding = 1) uniform sampler2D u_color;   // the HDR scene colour, read with texelFetch
layout(set = 0, binding = 2, rg16f) writeonly uniform image2D o_mv;
layout(set = 0, binding = 3, r32f) writeonly uniform image2D o_depth;
layout(set = 0, binding = 4, rgba16f) writeonly uniform image2D o_color;

layout(push_constant) uniform Push {
    mat4 reproj;       // current jittered NDC (x, y, z, 1) -> previous frame's unjittered clip space
    vec2 jitter;       // the current frame's jitter in NDC (subtracted from the current position)
    vec2 size;         // render size in pixels
    vec2 zmap;         // NDC z = depth * zmap.x + zmap.y
    vec2 pad;
} pc;

void main() {
    ivec2 p = ivec2(gl_GlobalInvocationID.xy);
    if (p.x >= int(pc.size.x) || p.y >= int(pc.size.y)) return;
    float d = texelFetch(u_depth, p, 0).r;
    // NDC +y is the top row (the replay draws with an upper-left origin and a flipped viewport)
    vec2 ndc = vec2((float(p.x) + 0.5) / pc.size.x * 2.0 - 1.0, 1.0 - (float(p.y) + 0.5) / pc.size.y * 2.0);
    vec4 h = pc.reproj * vec4(ndc, d * pc.zmap.x + pc.zmap.y, 1.0);
    vec2 mv = vec2(0.0);
    if (abs(h.w) > 1e-7) {
        vec2 dn = h.xy / h.w - (ndc - pc.jitter);
        mv = vec2(dn.x * 0.5, -dn.y * 0.5);   // UV units (y down), previous minus current
    }
    imageStore(o_mv, p, vec4(mv, 0.0, 0.0));
    imageStore(o_depth, p, vec4(d, 0.0, 0.0, 0.0));
    imageStore(o_color, p, vec4(max(texelFetch(u_color, p, 0).rgb, vec3(0.0)), 1.0));
}
"""

HEADER = """// GENERATED by scripts/gen_temporal_shaders.py: do not edit
// SPIR-V of the temporal upscalers' input pass, compiled with glslc -O --target-env=vulkan1.3 and checked with spirv-val --target-env vulkan1.3.
//
// kTemporalPrepComp: compute shader, local size 8 x 8 x 1: dispatch (ceil(w / 8), ceil(h / 8), 1).
//   Descriptors (set 0, compute stage): binding 0 COMBINED_IMAGE_SAMPLER (scene depth, depth aspect), binding 1 COMBINED_IMAGE_SAMPLER (HDR scene
//     colour), binding 2 STORAGE_IMAGE rg16f (motion vectors out: previous minus current position, UV units, y down), binding 3 STORAGE_IMAGE r32f
//     (depth copy out), binding 4 STORAGE_IMAGE rgba16f (colour copy out).
//   Push constants: 96 bytes: mat4 reproj (column-major), vec2 jitter (NDC), vec2 size (pixels), vec2 zmap (NDC z = d * x + y), vec2 pad.
"""


def main():
    glslc = tool("GLSLC", "glslc")
    spirv_val = tool("SPIRV_VAL", "spirv-val")
    with tempfile.TemporaryDirectory() as tmp:
        comp = os.path.join(tmp, "temporal_prep.comp")
        with open(comp, "w", newline="\n") as f:
            f.write(SRC)
        res = subprocess.run([glslc, "-O", "--target-env=vulkan1.3", "-o", "-", comp], capture_output=True)
        if res.returncode != 0:
            sys.stderr.write("glslc failed:\n%s" % res.stderr.decode(errors="replace"))
            sys.exit(1)
        spv = res.stdout
        if len(spv) % 4:
            sys.stderr.write("SPIR-V size is not a multiple of 4\n")
            sys.exit(1)
        path = os.path.join(tmp, "prep.spv")
        with open(path, "wb") as f:
            f.write(spv)
        v = subprocess.run([spirv_val, "--target-env", "vulkan1.3", path], capture_output=True, text=True)
        if v.returncode != 0:
            sys.stderr.write("spirv-val failed:\n%s\nFAILED: temporal_shaders.inc not written\n" % (v.stdout + v.stderr))
            sys.exit(1)
    words = [int.from_bytes(spv[i:i + 4], "little") for i in range(0, len(spv), 4)]
    lines = [HEADER, "static const uint32_t kTemporalPrepComp[] = {"]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    lines.append("};")
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d words)" % (out_path, len(words)))


if __name__ == "__main__":
    main()
